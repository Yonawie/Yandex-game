function seededPositions(seed, count, margin = 120) {
  let s = seed;
  const rnd = () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return s / 4294967296;
  };
  const pts = [];
  const cellW = 280;
  const cellH = 320;
  const cols = Math.floor((2800 - margin * 2) / cellW);
  const rows = Math.floor((3600 - margin * 2 - 400) / cellH);
  const cells = [];
  for (let r = 0; r < rows; r++) {
    for (let c = 0; c < cols; c++) cells.push([c, r]);
  }
  // shuffle
  for (let i = cells.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [cells[i], cells[j]] = [cells[j], cells[i]];
  }
  for (let i = 0; i < count; i++) {
    const [c, r] = cells[i % cells.length];
    const x = margin + c * cellW + 40 + rnd() * (cellW - 80);
    const y = 500 + margin + r * cellH + 40 + rnd() * (cellH - 80);
    pts.push({ x, y });
  }
  return pts;
}

