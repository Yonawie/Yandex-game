/** Build map placements: all items on the map with positions */
export function getMapPlacements(mapId) {
  const pool = MAP_ITEM_POOLS[mapId];
  const pts = seededPositions(MAP_SEEDS[mapId], pool.length);
  return pool.map((id, i) => ({
    id,
    x: pts[i].x,
    y: pts[i].y,
    ...ITEM_CATALOG[id],
  }));
}

/**
 * 3 levels per map. Each asks for many items (~15) from the pool.
 */
export function buildLevels() {
  const maps = Object.keys(MAP_ITEM_POOLS);
  const levels = [];
  maps.forEach((mapId, mapIndex) => {
    const pool = MAP_ITEM_POOLS[mapId];
    const chunk = Math.floor(pool.length / 3);
    for (let L = 0; L < 3; L++) {
      const start = L * chunk;
      const end = L === 2 ? pool.length : start + chunk;
      const targets = pool.slice(start, end);
      levels.push({
        id: `${mapId}_${L + 1}`,
        mapId,
        mapIndex,
        levelIndex: L,
        title: `Уровень ${L + 1}`,
        targetCount: targets.length,
        targets,
        difficulty: L === 0 ? "легко" : L === 1 ? "норма" : "сложно",
      });
    }
  });
  return levels;
}

export const LEVELS = buildLevels();

export function getLevelsForMap(mapId) {
  return LEVELS.filter((l) => l.mapId === mapId);
}

export function getLevelById(id) {
  return LEVELS.find((l) => l.id === id);
}
